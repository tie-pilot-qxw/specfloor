#!/usr/bin/env python3
"""Recompute the draft-forward table from archived CUDA-event samples, without GPUs.

Not a paper table: a fixed-state latency diagnostic of the draft forward alone.
"""
import argparse
import hashlib
import json
from pathlib import Path
import statistics


def build(data):
    manifest = json.loads((data / "manifest.json").read_text())
    batches, contexts = manifest["batches"], manifest["contexts"]
    assert contexts == [512, 1024], "table layout expects the two registered contexts"
    expected = {(b, c) for b in batches for c in contexts}
    records, sources = {}, {}
    for arm in ("official", "ours"):
        p = data / f"{arm}.jsonl"
        raw = p.read_bytes()
        sources[p.name] = hashlib.sha256(raw).hexdigest()
        seen = set()
        for line in raw.decode().splitlines():
            r = json.loads(line)
            key = (r["batch_size"], r["context_label"])
            assert r["arm"] == arm and key in expected and key not in seen
            assert r["prefix_lengths"] == [key[1]] * key[0]
            assert r["gamma"] == r["query_tokens"] == 7
            assert r["folded"] and r["fixed_state_output_stable"]
            assert r["graph_replay_count"] == 64 and r["warmup_iterations"] == 12
            assert len(r["draft_model_forward"]["samples_ms"]) == 64
            assert all(x > 0 for x in r["draft_model_forward"]["samples_ms"])
            seen.add(key)
            records[(arm, *key)] = r
        assert seen == expected

    rows = []
    for b in batches:
        for c in contexts:
            o, u = [records[(arm, b, c)] for arm in ("official", "ours")]
            om, um = [statistics.median(r["draft_model_forward"]["samples_ms"]) for r in (o,u)]
            rows.append(dict(batch=b, prefix_tokens=c, official_ms=om, ours_ms=um,
                             relative_time_change_percent=100*(um/om-1),
                             official_proposal_ms=statistics.median(o["full_proposal"]["samples_ms"]),
                             ours_proposal_ms=statistics.median(u["full_proposal"]["samples_ms"])))
    summary = dict(rows=rows, source_sha256=sources, statistic="median of 64 within-state CUDA-event samples",
                   unit="ms per draft forward", independent_launches_per_arm=1,
                   exclusions=["target verification", "commit_hidden", "HTTP", "prefill"])
    by_key = {(r["batch"],r["prefix_tokens"]): r for r in rows}
    lines = [
        "% Generated by serving/results/summarize_draft_forward_sweep.py; do not edit numbers.",
        r"\begin{table}[ht]",
        r"\centering\small",
        r"\caption{Median draft-forward latency (ms; lower is better) versus batch size.",
        r"Both methods use the same H100, BF16, seven speculative positions, and greedy decoding.",
        r"Each entry is the median of 64 CUDA-event measurements after warmup, with a fixed KV prefix.",
        r"The measured graph includes the folded proposal head; target verification and subsequent KV commit are excluded.",
        r"This measures draft cost, not end-to-end speedup.}",
        r"\label{tab:draft-forward-sweep}",
        r"\setlength{\tabcolsep}{9pt}",
        r"\begin{tabular}{rcccc}",
        r"\toprule",
        r" & \multicolumn{2}{c}{Prefix length 512} & \multicolumn{2}{c}{Prefix length 1024} \\",
        r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}",
        r"Batch & DSpark & Ours & DSpark & Ours \\",
        r"\midrule",
    ]
    for b in batches:
        cells = [f"{by_key[(b,c)][k]:.3f}" for c in contexts for k in ("official_ms","ours_ms")]
        lines.append(f"{b} & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    return summary, "\n".join(lines)


def main():
    here = Path(__file__).resolve().parent
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--data", type=Path, default=here / "draft_forward_sweep")
    ap.add_argument("--out", type=Path, default=here / "generated")
    args = ap.parse_args()
    summary, table = build(args.data)
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "draft_forward_sweep.tex").write_text(table)
    (args.out / "draft_forward_summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
