#!/usr/bin/env python3
"""Verify the archived serving rows and regenerate the paper's serving tables.

    python summarize_serving_sweep.py            # writes generated/

Checks every raw row against the prepared requests (identity, prompt tokens,
sampling settings, finish reasons), recomputes every per-task summary from the
rows, checks the recorded comparisons and source hashes, and then writes:

  generated/serving_sweep.tex            tab:serving-sweep (all 30 points)
  generated/solution_serving.tex         tab:solution-serving (main text)
  generated/solution_serving_details.tex tab:solution-serving-details (per task)
  generated/acceptance_summary.json      five-concurrency accepted length

Accepted length averages each task over C = 1/4/8/16/32, then the nine tasks;
speedup S is the C=1 point, the sequential-request setting. No GPU is used.
"""
import argparse
import gzip
import hashlib
import json
import math
from pathlib import Path
import statistics

TASKS = {'gsm8k': 500, 'math500': 500, 'aime25': 30, 'humaneval': 164,
         'mbpp': 256, 'livecodebench': 500, 'mt-bench': 80, 'alpaca': 500,
         'arena-hard-v2': 500}
LABELS = dict(zip(TASKS, ['GSM8K', 'MATH-500', 'AIME25', 'HumanEval', 'MBPP',
                        'LiveCodeBench', 'MT-Bench', 'Alpaca', 'Arena-Hard-v2']))
CS = [1, 4, 8, 16, 32]


def build(data):
    index = json.loads((data / 'archive.json').read_text())
    prepared_raw = gzip.decompress((data / 'prepared_requests.jsonl.gz').read_bytes())
    assert hashlib.sha256(prepared_raw).hexdigest() == index['prepared_requests_sha256']
    prepared = [json.loads(s) for s in prepared_raw.splitlines()]
    identity = lambda r: (r['dataset'], r['idx'], r['prompt_sha1'], r['input_ids_sha256'])
    expected = {identity(r): len(r['input_ids']) for r in prepared}
    assert len(expected) == len(prepared) == 3030
    records = {}
    for point in index['points']:
        t, c, arm = point['temperature'], point['concurrency'], point['arm']
        raw = gzip.decompress((data / point['raw']).read_bytes())
        assert hashlib.sha256(raw).hexdigest() == point['raw_sha256']
        rows = [json.loads(s) for s in raw.splitlines()]
        marker = json.loads((data / point['complete']).read_text())
        assert marker['complete'] and marker['rows'] == len(rows) == 3030
        assert len({identity(r) for r in rows}) == len(rows)
        assert {identity(r) for r in rows} == set(expected)
        summaries = json.loads((data / point['summary']).read_text())
        assert set(summaries) == set(TASKS)
        for row in rows:
            assert row['arm'] == arm and row['concurrency'] == c and row['temperature'] == t
            if t == 1:
                assert row['sampling_seed'] == 980406
            meta = row['meta_info']
            assert meta['prompt_tokens'] == row['expected_prompt_tokens'] == expected[identity(row)]
            assert meta.get('num_retractions', 0) == meta.get('cached_tokens', 0) == 0
            assert meta['finish_reason']['type'] in ('stop', 'length')
            assert row['completion_tokens'] > 0 and row['scheduler_decode_elapsed_s'] >= 0
            if row['completion_tokens'] > 1:
                assert row['scheduler_decode_elapsed_s'] > 0
                if arm != 'baseline':
                    assert row['spec_verify_ct'] > 0
        for task, count in TASKS.items():
            selected = [r for r in rows if r['dataset'] == task]
            s = summaries[task]
            assert len(selected) == s['rows'] == count
            n = sum(r['completion_tokens'] for r in selected)
            v = sum(r.get('spec_verify_ct') or 0 for r in selected)
            decode = sum(r['scheduler_decode_elapsed_s'] for r in selected)
            assert n == s['completion_tokens'] and v == s['verification_steps']
            assert s['elapsed_s'] > 0
            for actual, target in [(n / s['elapsed_s'], s['system_output_tokens_per_second']),
                                   (decode, s['summed_scheduler_decode_elapsed_s']),
                                   ((n-count) / decode, s['per_request_decode_tokens_per_second'])]:
                assert math.isclose(actual, target, rel_tol=1e-12)
            assert s['post_prefill_output_tokens'] == n-count
            assert s['accepted_length'] == (n/v if v else None)
        key = (t, c, arm)
        assert key not in records
        records[key] = summaries
    assert len(records) == 30
    for run in index['runs'].values():
        manifest = json.loads((data / run['manifest']).read_text())
        for source, local in run['sources'].items():
            assert hashlib.sha256((data / local).read_bytes()).hexdigest() == manifest['source_sha256'][source]
    acceptance = {}
    c1_speedups = {}
    table = [r'% Generated by serving/results/summarize_serving_sweep.py.', r'\begin{table}[ht]',
             r'\centering\small',
             r'\caption{Serving sweep with exact end-to-end timing, including prefill and HTTP.',
             r'Each speedup is an equal mean of nine task-level ratios. $C$ denotes request concurrency.}',
             r'\label{tab:serving-sweep}', r'\setlength{\tabcolsep}{5pt}',
             r'\begin{tabular}{rrrrrrr}', r'\toprule',
             r'$T$ & $C$ & $S$ DSpark & $S$ Ours & Ours/DSpark gain & $\tau$ DSpark & $\tau$ Ours \\',
             r'\midrule']
    for t in [0, 1]:
        comp = json.loads((data / f'temp{t}/comparison.json').read_text())
        c1_speedups[str(t)] = comp['1']
        for c in CS:
            rates = {a: {n: records[t,c,a][n]['system_output_tokens_per_second'] for n in TASKS}
                     for a in ['baseline', 'official', 'ours']}
            for a in ['official', 'ours']:
                ratios = {n: rates[a][n]/rates['baseline'][n] for n in TASKS}
                assert ratios == comp[str(c)]['per_task_speedup_over_ar'][a]
                assert statistics.mean(ratios.values()) == comp[str(c)]['macro_speedup_over_ar'][a]
            gain = statistics.mean(rates['ours'][n]/rates['official'][n] for n in TASKS)
            assert gain == comp[str(c)]['mean_task_ours_over_official']
            taus = {a: statistics.mean(records[t,c,a][n]['accepted_length'] for n in TASKS)
                    for a in ['official', 'ours']}
            assert taus == comp[str(c)]['macro_accepted_length']
            speeds = comp[str(c)]['macro_speedup_over_ar']
            table.append(f'{t} & {c} & {speeds["official"]:.3f} & {speeds["ours"]:.3f} & '
                         f'$+{(gain-1)*100:.2f}\\%$ & {taus["official"]:.3f} & {taus["ours"]:.3f} ' + r'\\')
        acceptance[str(t)] = {}
        for a in ['official', 'ours']:
            task_means = {n: statistics.mean(records[t,c,a][n]['accepted_length'] for c in CS) for n in TASKS}
            point_macros = [statistics.mean(records[t,c,a][n]['accepted_length'] for n in TASKS) for c in CS]
            acceptance[str(t)][a] = dict(per_task=task_means, macro=statistics.mean(task_means.values()),
                macro_by_concurrency=dict(zip(map(str,CS), point_macros)),
                min_macro=min(point_macros), max_macro=max(point_macros))
        if t == 0:
            table.append(r'\midrule')
    table += [r'\bottomrule', r'\end{tabular}', r'\end{table}', '']
    return acceptance, '\n'.join(table), c1_speedups


def solution_tables(acceptance, c1_speedups):
    """The main-text and per-task tables, in the paper's layout and rounding."""
    def cells(t, arm, task=None):
        d, speeds = acceptance[str(t)][arm], c1_speedups[str(t)]
        tau = d['per_task'][task] if task else d['macro']
        s = (speeds['per_task_speedup_over_ar'][arm][task] if task
             else speeds['macro_speedup_over_ar'][arm])
        return tau, s
    bold = lambda v, arm: v if arm == 'official' else r'\textbf{' + v + '}'
    main = []
    for arm, name in [('official', 'DSpark'), ('ours', 'Ours')]:
        row = [name]
        for t in [0, 1]:
            tau, s = cells(t, arm)
            row += [bold(f'{tau:.2f}', arm), '$' + f'{s:.2f}' + r'\times$' if arm == 'official'
                    else r'$\mathbf{' + f'{s:.2f}' + r'}\times$']
        main.append(' & '.join(row) + r' \\')
    details = []
    for task in [*TASKS, None]:
        row = [LABELS[task] if task else 'Macro', str(TASKS[task] if task else sum(TASKS.values()))]
        for t in [0, 1]:
            vals = {arm: cells(t, arm, task) for arm in ['official', 'ours']}
            fmt = '{:.3f}' if task else '{:.2f}'
            row += [bold(fmt.format(vals[a][0]), a) for a in ['official', 'ours']]
            row += [bold(f'{vals[a][1]:.2f}', a) for a in ['official', 'ours']]
        details.append(' & '.join(row) + r' \\')
    header = '% Generated by serving/results/summarize_serving_sweep.py; table body rows only.'
    return '\n'.join([header, *main, '']), '\n'.join([header, *details, ''])


def main():
    here = Path(__file__).resolve().parent
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--data', type=Path, default=here / 'serving_sweep_20260922')
    ap.add_argument('--out', type=Path, default=here / 'generated')
    args = ap.parse_args()
    acceptance, table, c1_speedups = build(args.data)
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / 'acceptance_summary.json').write_text(json.dumps(dict(
        aggregation='Equal mean over C=1/4/8/16/32 within each task, then equal mean over nine tasks; distinct conditions, not five independent repetitions.',
        temperatures=acceptance), indent=2)+'\n')
    (args.out / 'serving_sweep.tex').write_text(table)
    main_rows, detail_rows = solution_tables(acceptance, c1_speedups)
    (args.out / 'solution_serving.tex').write_text(main_rows)
    (args.out / 'solution_serving_details.tex').write_text(detail_rows)
    print('Validated 30 points / 90,900 rows and source snapshots; regenerated tables in', args.out)
    print(json.dumps({t:{a:v['macro'] for a,v in d.items()} for t,d in acceptance.items()},indent=2))


if __name__ == '__main__':
    main()
